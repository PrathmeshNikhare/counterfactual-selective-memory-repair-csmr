"""Write docs/seed_review.md (the test-split seed families, for human review) from data/seeds/.

  python eval/render_seed_review.py

eval/validate_dataset.py fails while the committed file differs from what this renders."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from csmr.config import ROOT

REVIEW = ROOT / "docs/seed_review.md"


def _cell(s) -> str:
    return str(s).replace("|", "\\|")


def render(seed_dir: Path = ROOT / "data/seeds") -> str:
    fams = {f["family_id"]: f for f in json.loads((seed_dir / "seeds.json").read_text("utf-8"))["families"]}
    test = json.loads((seed_dir / "splits.json").read_text("utf-8"))["test"]
    out = ["# Seed review: test families", "",
           f"The {len(test)} test-split families from `data/seeds/seeds.json`. Generated by "
           "`python eval/render_seed_review.py`: edit the JSON, not this file. Labeling and gold-answer conventions: "
           "`docs/DATASET_NOTE.md`. *pending* = the answer comes from a VERIFY memory (the QA judge is told).", ""]
    out += [f"- [{i}](#{i})" for i in test] + [""]
    for fid in test:
        f = fams[fid]
        out += [f"## {fid}", "", f"*{f['category']} · {f['domain']}* — {f['pattern']}", "",
                f"**Observation** ({f['observation']['source']}): \"{f['observation']['text']}\"", "",
                "| id | gold | role | text |", "|---|---|---|---|"]
        out += [f"| {m['id']} | {m['gold_action']} | {m['role']} | {_cell(m['text'])} |" for m in f["core_memories"]]
        deps = ", ".join(f"{a}→{b}" for a, b in f["dependencies"]) or "none"
        out += ["", f"**Dependencies:** {deps}", "", "**Forbidden** (must not be added as hard negative or filler):"]
        out += [f"- {x}" for x in f["forbidden"]]
        out += ["", "**Eval questions**", "", "| question | gold answer | depends on | pending |", "|---|---|---|---|"]
        out += [f"| {_cell(q['q'])} | {_cell(q['gold_answer'])} | {', '.join(q['depends_on'])} | "
                f"{'yes' if q.get('pending') else ''} |" for q in f["eval_questions"]]
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    REVIEW.write_text(render(), encoding="utf-8")
    print(f"wrote {REVIEW.relative_to(ROOT)}")
